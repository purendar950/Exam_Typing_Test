/**
 * One-off maintenance script (run: node scripts/split_passages.mjs).
 *
 * Splits src/data/passages.ts:
 *  - PASSAGES keeps only metadata (titles, numbers, language, ...) so the boot
 *    bundle stays small.
 *  - The full text of the bundled free demo tests (Tests #1-7) moves to
 *    src/data/passagesFreeText.ts, a lazy chunk loaded when a test starts.
 * Lessons (MANGAL_LESSONS / ENGLISH_LESSONS) are kept untouched in passages.ts.
 */
import fs from 'node:fs';

const SRC = 'src/data/passages.ts';
const src = fs.readFileSync(SRC, 'utf8');

const lessons = src.slice(src.indexOf('export const MANGAL_LESSONS'));

let code = src.replace(/^import[^\n]*\n/m, '').replace(/export const PASSAGES: Passage\[\] =/, 'export const PASSAGES =');
fs.writeFileSync('/data/user/0/com.termux/files/usr/tmp/opencode/passages_eval.mjs', code);
const mod = await import('/data/user/0/com.termux/files/usr/tmp/opencode/passages_eval.mjs');
const passages = mod.PASSAGES;
if (!Array.isArray(passages) || passages.length < 100) {
  console.error('Unexpected passages array, aborting.');
  process.exit(1);
}

if (src.includes('text is in passagesFreeText.ts')) {
  console.error('src/data/passages.ts is already split (no bundled texts). Nothing to do.');
  process.exit(1);
}
const freeText = {};
let textCount = 0;
for (const p of passages) {
  if (p.text && p.text.trim()) {
    freeText[p.id] = p.text;
    textCount++;
  }
  p.text = '';
}

const meta = passages.map((p) => '  ' + JSON.stringify(p)).join(',\n');
fs.writeFileSync(
  SRC,
  '/**\n' +
    ' * Metadata only. Full text is NOT shipped in the boot bundle:\n' +
    ' *  - Tests #1-7 (free demos): text is in passagesFreeText.ts (lazy chunk).\n' +
    ' *  - Tests #8+ (paid): fetched on demand from Firestore (/paid_passages/{id}).\n' +
    ' * Regenerate with: node scripts/split_passages.mjs (after updating a source file).\n' +
    ' */\n' +
    "import { Passage } from '../types';\n\n" +
    'export const PASSAGES: Passage[] = [\n' +
    meta +
    '\n];\n\n' +
    lessons
);
fs.writeFileSync(
  'src/data/passagesFreeText.ts',
  '// Auto-generated by scripts/split_passages.mjs — do not edit by hand.\n' +
    '// Full text of the free demo tests (Tests #1-7) that used to ship in the boot\n' +
    '// bundle. Loaded only after the site has painted, and at test start.\n' +
    'export const FREE_PASSAGE_TEXT: Record<string, string> = ' +
    JSON.stringify(freeText, null, 0) +
    ';\n'
);
console.log(`Split done: ${passages.length} passages, ${textCount} bundled texts extracted.`);
